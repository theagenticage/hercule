  readonly id: string;
  readonly source: FableSourceId;
  readonly place: string;
  readonly kind: string;
  readonly ident: string;
  readonly title: string;
  readonly status: string;
  readonly stage: FableStage;
  readonly need: FableNeed;
  readonly reason: string;
  readonly person: string;
  /** Minutes since it last changed at its source. */
  readonly ageMin: number;
  /** Changed since the user last looked at the Inbox. */
  readonly isNew: boolean;
  readonly fact?: string;
  /** Events per day over the last two weeks, for a Sentry error. */
  readonly trend?: readonly number[];
