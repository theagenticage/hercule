/**
 * The sizes the lists that sit beside an open item draw their headings and
 * rows at: Workflows, Discussions and Wiki. Each list places its items by
 * these heights, so they are the same numbers the rows' CSS draws.
 */

/** The height of a group's heading, in CSS pixels, without the space above it. */
export const GROUP_HEADING_HEIGHT = 24;

/** The height of a one-line row in the table, in CSS pixels. */
export const ONE_LINE_ROW_HEIGHT = 40;

/** The height of a row in the column, in CSS pixels, without the space above it. */
export const COLUMN_ROW_HEIGHT = 46;

/** The space above each of the column's rows, in CSS pixels, as between the sidebar's rows. */
export const COLUMN_ROW_LEADING = 1;
