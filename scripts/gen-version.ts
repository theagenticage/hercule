/**
 * Write `packages/home/src/version.ts`.
 *
 * The version is baked in at build time: a compiled binary has no
 * `package.json` on disk to read. It is generated into
 * `@hydra/home` because that is the one leaf every role links: the dispatcher
 * prints it for `hydra --version` and the controller answers it from
 * `controller.read`, and neither may depend on the other.
 *
 * The Claude Code version is baked in beside it, and for the same reason. The
 * Agent SDK talks to the CLI it was built against and to anything newer, so
 * that CLI's version is both the floor a machine is held to and the newest one
 * anybody has tested. It is the SDK's own `claudeCodeVersion`, so it moves only
 * when the dependency moves - which is a deliberate, reviewed change - and it
 * is written down here and nowhere else.
 */
import { fileURLToPath } from "node:url";
import { $ } from "bun";

const root = fileURLToPath(new URL("..", import.meta.url));
const { version } = (await Bun.file(`${root}package.json`).json()) as { version: string };
const sha = (await $`git rev-parse --short HEAD`.cwd(root).nothrow().quiet().text()).trim();
const { claudeCodeVersion } = (await Bun.file(
  `${root}apps/runner/node_modules/@anthropic-ai/claude-agent-sdk/package.json`,
).json()) as { claudeCodeVersion: string };

await Bun.write(
  `${root}packages/home/src/version.ts`,
  `/** Generated by scripts/gen-version.ts. Do not edit. */
export const VERSION = ${JSON.stringify(sha ? `${version}+${sha}` : version)};

/** The Claude Code CLI version the Agent SDK in this build was built against. */
export const CLAUDE_CODE_VERSION = ${JSON.stringify(claudeCodeVersion)};
`,
);
